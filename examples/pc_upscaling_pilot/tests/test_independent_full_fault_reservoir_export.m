        "fault_local_to_reservoir_grid_signed_yz_v1", ...
    'pre_rotated', false, ...
    'tensor_formula', ...
        "K_global = R * diag(K_local) * transpose(R)", ...
    'component_formula', "documented component mapping", ...
    'geometry_dependency', "one signed angle per fault cell");
end
