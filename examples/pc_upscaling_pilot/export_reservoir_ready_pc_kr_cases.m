function validateSamplingCaseRole(caseMetadata)
caseType = string(caseMetadata.caseType);
switch caseType
    case "independent_full"
        expected = [true, false, false];
        assert(caseMetadata.replicateId >= 1 && ...
            caseMetadata.replicateId <= 52, ...
            'ReservoirReady:SamplingReplicate', ...
            'Independent replicate ID must lie in 1:52.');
    case "representative_medoid"
        expected = [false, true, false];
        assert(caseMetadata.replicateId == 0, ...
            'ReservoirReady:SamplingReplicate', ...
            'Representative benchmark must use replicate ID 0.');
    case {"low_state_stress", "high_state_stress"}
        expected = [false, false, true];
        assert(caseMetadata.replicateId == 0, ...
            'ReservoirReady:SamplingReplicate', ...
            'Stress benchmarks must use replicate ID 0.');
    otherwise
        error('ReservoirReady:SamplingCaseType', ...
            'Unsupported revised sampling case type: %s', caseType);
end
actual = [caseMetadata.useForProbabilisticUq, ...
    caseMetadata.isBenchmark, caseMetadata.isStressTest];
assert(isequal(actual, expected), 'ReservoirReady:SamplingCaseRole', ...
    'Sampling role flags do not match case type %s.', caseType);
assert(strlength(caseMetadata.samplingCaseId) > 0, ...
    'ReservoirReady:SamplingCaseId', ...
    'Explicit revised sampling metadata requires a sampling case ID.');
end


