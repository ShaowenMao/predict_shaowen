function tf = isSha256(value)
% Return true only for one lowercase or uppercase hexadecimal SHA-256 value.

value = char(string(value));
tf = ~isempty(regexp(value, '^[0-9a-fA-F]{64}$', 'once'));
end


function value = sha256File(file)
% Compute SHA-256 incrementally without loading a complete file into memory.

file = char(string(file));
fid = fopen(file, 'rb');
assert(fid >= 0, 'ReservoirReady:ReplayManifestHashRead', ...
    'Could not open file for hashing: %s', file);
cleanup = onCleanup(@() fclose(fid));
digest = java.security.MessageDigest.getInstance('SHA-256');
while true
    bytes = fread(fid, 1024 * 1024, '*uint8');
    if isempty(bytes)
        break
    end
    digest.update(bytes);
end
bytes = typecast(digest.digest(), 'uint8');
value = lower(string(reshape(dec2hex(bytes, 2).', 1, [])));
clear cleanup
end


