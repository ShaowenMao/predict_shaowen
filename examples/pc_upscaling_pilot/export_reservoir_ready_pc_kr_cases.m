function [permeability, sourceLogMismatch] = extractEffectivePermeability( ...
        fieldPerm, geologyId, caseId, windows, slices, tolerance)
% Extract and validate one case as window-by-slice-by-component arrays.

geologyLabels = string(fieldPerm.geology_id(:));
caseLabels = double(fieldPerm.level3_case_id(:));
sliceLabels = double(fieldPerm.slice_index(:));
windowLabels = string(fieldPerm.window(:));
componentLabels = string(fieldPerm.component(:));

g = find(geologyLabels == string(geologyId));
c = find(caseLabels == double(caseId));
[sliceFound, s] = ismember(double(slices(:)), sliceLabels);
[windowFound, w] = ismember(string(windows(:)), windowLabels);
requestedComponents = ["kxx"; "kyy"; "kzz"];
[componentFound, componentIndex] = ismember( ...
    requestedComponents, componentLabels);
assert(isscalar(g) && isscalar(c), ...
    'ReservoirReady:PermeabilityCaseLookup', ...
    'Permeability input lacks one unique match for %s case %02d.', ...
    geologyId, caseId);
assert(all(sliceFound) && all(windowFound) && all(componentFound), ...
    'ReservoirReady:PermeabilityAxisLookup', ...
    ['Permeability input lacks one or more requested slices, windows, ', ...
     'or components for %s case %02d.'], geologyId, caseId);

expectedSize = [numel(geologyLabels), numel(caseLabels), ...
    numel(sliceLabels), numel(windowLabels), numel(componentLabels)];
assert(isequal(size(fieldPerm.perm), expectedSize) && ...
    isequal(size(fieldPerm.logK), expectedSize), ...
    'ReservoirReady:PermeabilityArraySize', ...
    'fieldPerm permeability arrays do not match their labeled dimensions.');

nSlices = numel(s);
nWindows = numel(w);
rawMD = fieldPerm.perm(g, c, s, w, componentIndex);
rawLog = fieldPerm.logK(g, c, s, w, componentIndex);
mD = permute(reshape(double(rawMD), ...
    [nSlices, nWindows, numel(componentIndex)]), [2, 1, 3]);
sourceLog10mD = permute(reshape(double(rawLog), ...
    [nSlices, nWindows, numel(componentIndex)]), [2, 1, 3]);
assert(all(isfinite(mD), 'all') && all(mD > 0, 'all') && ...
    all(isfinite(sourceLog10mD), 'all'), ...
    'ReservoirReady:InvalidPermeability', ...
    'Permeability values must be positive and finite.');

sourceLogMismatch = max(abs(sourceLog10mD - log10(mD)), [], 'all');
assert(sourceLogMismatch <= tolerance, ...
    'ReservoirReady:PermeabilityLogMismatch', ...
    ['Stored log10 permeability differs from log10(mD) by %.3g for ', ...
     '%s case %02d.'], sourceLogMismatch, geologyId, caseId);

sampleRaw = fieldPerm.selected_sample_index(g, c, s, w);
seedRaw = fieldPerm.exact_replay_seed(g, c, s, w);
selectedSampleIndex = permute(reshape(sampleRaw, ...
    [nSlices, nWindows]), [2, 1]);
exactReplaySeed = permute(reshape(seedRaw, ...
    [nSlices, nWindows]), [2, 1]);
assert(all(selectedSampleIndex > 0, 'all') && ...
    all(exactReplaySeed > 0, 'all'), ...
    'ReservoirReady:InvalidReplayMetadata', ...
    'Selected sample indices and replay seeds must be positive.');

assignedState = reshape(string(fieldPerm.assigned_state(g, c, w)), ...
    [nWindows, 1]);
samplingPool = reshape(string(fieldPerm.sampling_pool(g, c, w)), ...
    [nWindows, 1]);

hasRevisedAssignmentMetadata = all(isfield(fieldPerm, { ...
    'predict_realization_id', 'sampling_seed', 'checkpoint_sha256', ...
    'checkpoint_relative_path'}));
if hasRevisedAssignmentMetadata
    realizationRaw = fieldPerm.predict_realization_id(g, c, s, w);
    predictRealizationId = permute(reshape(realizationRaw, ...
        [nSlices, nWindows]), [2, 1]);
    samplingSeed = reshape(fieldPerm.sampling_seed(g, c, w), ...
        [nWindows, 1]);
    checkpointSha256 = reshape(string(fieldPerm.checkpoint_sha256(g, w)), ...
        [nWindows, 1]);
    checkpointRelativePath = reshape(string( ...
        fieldPerm.checkpoint_relative_path(g, w)), [nWindows, 1]);
    if isfield(fieldPerm, 'source_checkpoint_file')
        sourceCheckpointFile = reshape(string( ...
            fieldPerm.source_checkpoint_file(g, w)), [nWindows, 1]);
    else
        sourceCheckpointFile = strings(nWindows, 1);
    end
    assert(all(predictRealizationId > 0, 'all') && ...
        all(samplingSeed >= 0, 'all'), ...
        'ReservoirReady:InvalidSamplingMetadata', ...
        'PREDICT realization IDs and sampling seeds are invalid.');
    assert(all(cellfun(@isSha256, cellstr(checkpointSha256))), ...
        'ReservoirReady:CheckpointHash', ...
        'Every revised-design window must have a valid checkpoint SHA-256.');
    assert(all(strlength(checkpointRelativePath) > 0), ...
        'ReservoirReady:CheckpointPath', ...
        'Every revised-design window must have a checkpoint-relative path.');
else
    predictRealizationId = selectedSampleIndex;
    samplingSeed = zeros(nWindows, 1, 'int64');
    checkpointSha256 = strings(nWindows, 1);
    checkpointRelativePath = strings(nWindows, 1);
    sourceCheckpointFile = strings(nWindows, 1);
end

permeability = struct();
permeability.dimensionOrder = "window x slice x component";
permeability.componentLabels = requestedComponents;
permeability.units = struct('mD', "millidarcy", ...
    'squareMeters', "m^2");
permeability.mD = mD;
permeability.squareMeters = mD .* 9.869233e-16;
permeability.selectedSampleIndex = selectedSampleIndex;
permeability.predictRealizationId = predictRealizationId;
permeability.exactReplaySeed = exactReplaySeed;
permeability.samplingSeed = samplingSeed;
permeability.checkpointSha256 = checkpointSha256;
permeability.checkpointRelativePath = checkpointRelativePath;
permeability.sourceCheckpointFile = sourceCheckpointFile;
permeability.assignmentMetadataExplicit = hasRevisedAssignmentMetadata;
permeability.assignedState = assignedState;
permeability.samplingPool = samplingPool;
permeability.coordinateFrame = "fault_local";
permeability.componentMeanings = ["fault_normal"; ...
    "along_strike"; "down_dip"];
permeability.rotationApplied = false;
permeability.transformRequired = true;
permeability.coordinateContract = extractCoordinateContract(fieldPerm);
permeability.samplingCase = extractSamplingCase(fieldPerm, g, c);
end


function contract = extractCoordinateContract(fieldPerm)
% Preserve the explicit fault-local tensor contract for downstream rotation.

if isfield(fieldPerm, 'coordinate_contract')
    source = fieldPerm.coordinate_contract;
    required = {'schema_version', 'stored_coordinate_system', ...
        'component_labels', 'component_meanings', ...
        'reservoir_coordinate_system', 'rotation_required', ...
        'downstream_transform_contract', 'pre_rotated', ...
        'tensor_formula', 'component_formula', 'geometry_dependency'};
    missing = required(~isfield(source, required));
    assert(isempty(missing), 'ReservoirReady:CoordinateContractFields', ...
        'fieldPerm coordinate contract is missing fields: %s', ...
        strjoin(missing, ', '));
    contract = source;
else
    % Legacy fieldPerm files store the same PREDICT-local components but did
    % not describe the frame explicitly. Keep support while making the
    % downstream transformation requirement unambiguous.
    contract = defaultFaultLocalCoordinateContract();
    contract.sourceMetadataStatus = "inferred_from_legacy_fieldPerm";
end

assert(logical(contract.rotation_required), ...
    'ReservoirReady:CoordinateRotationRequired', ...
    'Fault-local permeability must require downstream coordinate rotation.');
assert(~logical(contract.pre_rotated), ...
    'ReservoirReady:CoordinatePreRotation', ...
    'fieldPerm must contain unrotated PREDICT fault-local components.');
assert(string(contract.downstream_transform_contract) == ...
    "fault_local_to_reservoir_grid_signed_yz_v1", ...
    'ReservoirReady:CoordinateTransformVersion', ...
    'Unexpected downstream permeability-transform contract.');
end


function contract = defaultFaultLocalCoordinateContract()
contract = struct( ...
    'schema_version', "fault_local_coordinate_contract_v1", ...
    'stored_coordinate_system', ...
        "PREDICT fault-local orthonormal axes", ...
    'component_labels', ["kxx"; "kyy"; "kzz"], ...
    'component_meanings', ...
        ["fault_normal"; "along_strike"; "down_dip"], ...
    'reservoir_coordinate_system', "reservoir-grid Cartesian axes", ...
    'rotation_required', true, ...
    'downstream_transform_contract', ...
        "fault_local_to_reservoir_grid_signed_yz_v1", ...
    'global_x_mapping', ...
        "reservoir Kxx equals fault-local kyy (along strike)", ...
    'yz_rotation', ...
        "theta = sign(dY/dZ) * (dip_deg - 90 deg)", ...
    'tensor_formula', ...
        "K_global = R * diag(kxx_local, kyy_local, kzz_local) * transpose(R)", ...
    'component_formula', ...
        ["Kxx=kyy; Kyy=cos(theta)^2*kxx+sin(theta)^2*kzz; ", ...
         "Kyz=cos(theta)*sin(theta)*(kxx-kzz); ", ...
         "Kzz=sin(theta)^2*kxx+cos(theta)^2*kzz; Kxy=Kxz=0"], ...
    'pre_rotated', false, ...
    'geometry_dependency', ...
        ["theta must be calculated from the paired fault-node trace ", ...
         "for each reservoir fault cell"]);
