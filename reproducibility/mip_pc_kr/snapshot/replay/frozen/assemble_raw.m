function assemble_raw(manifest,out)
% A lossless review package, deliberately NOT a reservoirReady drop-in file.
M=jsondecode(fileread(manifest));D=load(M.baseline_mat,'reservoirReady');B=D.reservoirReady;
assert(numel(M.records)==522);raw=cell(6,87);audits=raw;identity=raw;seen=false(6,87);
for j=1:522
    x=M.records(j);w=x.window;s=x.slice;assert(~seen(w,s));seen(w,s)=true;
    C=readmatrix(x.curve,'NumHeaderLines',1);assert(isequal(size(C),[100,8]));
    assert(B.predictRealizationIdMap(w,s)==x.sample);
    assert(B.effectivePermeability.exactReplaySeed(w,s)==x.seed);
    raw{w,s}=C;audits{w,s}=jsondecode(fileread(x.audit));identity{w,s}=x;
end
assert(all(seen,'all'));
candidateRaw=struct('schema','candidate_full_fault_parametric_pc_kr_v1','geologyId',B.geologyId, ...
    'level3CaseId',B.level3CaseId,'windowLabels',B.windowLabels,'sliceIndices',B.sliceIndices,'windowSliceMap',B.windowSliceMap, ...
    'columnNames',{{'PcPa','physicalBulkSg','Krw','Krg','trappedPvFraction','immobilePvFraction', ...
    'gasBreakthrough','invadedPvFraction'}},'rawCurves',{raw},'exportAudits',{audits},'identities',{identity}, ...
    'Kxx_SI',B.Kxx_SI,'Kyy_SI',B.Kyy_SI,'Kzz_SI',B.Kzz_SI, ...
    'productionUpscaledPorosity',B.upscaledPorosity,'coordinateContract',B.effectivePermeability.coordinateContract, ...
    'predictRealizationIdMap',B.predictRealizationIdMap,'candidateSourceSha256',M.source, ...
    'reservoirExportApproved',false,'productionPromotion',false, ...
    'saturationMeaning','physical bulk Sg, including pre-breakthrough gas', ...
    'endpointMeaning','last sampled state; not an imposed residual-water endpoint');
assert(~isfolder(out));mkdir(out);file=fullfile(out,'candidate_raw_s03_c022_case12.mat');
save(file,'candidateRaw','-v7.3');V=load(file,'candidateRaw');assert(isequaln(candidateRaw,V.candidateRaw));
assert(isequaln(candidateRaw.Kzz_SI,B.Kzz_SI)&&isequaln(candidateRaw.coordinateContract,B.effectivePermeability.coordinateContract));
fid=fopen(fullfile(out,'roundtrip.json'),'w');fprintf(fid,'%s\n',jsonencode(struct('passed',true, ...
    'assignments',522,'all_raw_points_preserved',true,'production_K_unchanged',true, ...
    'production_mapping_unchanged',true,'reservoir_export_approved',false)));fclose(fid);
end
